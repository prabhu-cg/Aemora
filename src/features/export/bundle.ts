import { kebab } from '../../lib/kebab'
import { createZip, type ZipFile } from '../../lib/zip'
import type { ComponentDef } from '../components/schema'
import { resolveDialog } from '../dialog/ops'
import { resolveComponent } from '../mapping/engine'
import { exportProjectJson } from '../projects/repo'
import type { Project } from '../projects/schema'
import { generateXml, type XmlFormat } from '../xml/build'
import { validateAll, type ValidationSummary } from '../xml/validate'

export interface ComponentExport {
  component: ComponentDef
  /** Folder name under /apps/<project>/components. */
  folder: string
  format: XmlFormat
  /** Path inside the ZIP, and where it belongs in an AEM project. */
  zipPath: string
  aemPath: string
  /** Name used when downloading this one file on its own. */
  filename: string
  xml: string
  /** True when this is hand-edited XML rather than freshly generated. */
  edited: boolean
  validation: ValidationSummary
  counts: { syntaxOk: boolean; generatorErrors: number; generatorWarnings: number; aemErrors: number | null; aemWarnings: number | null }
}

/** One folder per component. A repeated name gets a numeric suffix so nothing is overwritten. */
export function componentFolders(project: Pick<Project, 'components' | 'aemComponentName'>): string[] {
  const used = new Set<string>()
  return project.components.map((c) => {
    const base = project.components.length === 1 && project.aemComponentName ? project.aemComponentName : kebab(c.name, 'component')
    let name = base
    for (let i = 2; used.has(name); i++) name = `${base}-${i}`
    used.add(name)
    return name
  })
}

/**
 * What each component exports: the hand-edited XML when there is one, otherwise the XML generated
 * from the current design. This is exactly what the XML tab shows.
 */
export function componentExports(project: Project): ComponentExport[] {
  const apps = kebab(project.name, 'project')
  const folders = componentFolders(project)
  return project.components.map((component, i) => {
    const folder = folders[i]
    const stored = project.generatedXml?.[component.id]
    const format: XmlFormat = stored?.edited ? stored.format : 'standalone'
    const fields = resolveComponent(component, project.mappings)
    const dialog = resolveDialog(component, project.dialog?.components?.[component.id])
    const xml = stored?.edited ? stored.xml : generateXml({ component, dialog, fields, projectName: project.name, componentFolder: folder, format })
    const validation = validateAll(xml, component, dialog, fields, !!project.aemComponentName || project.components.length > 1)
    const rel = format === 'standalone' ? `${folder}/_cq_dialog/.content.xml` : `${folder}/.content.xml`
    const g = validation.generator
    return {
      component, folder, format, xml, edited: !!stored?.edited, validation,
      zipPath: `jcr_root/apps/${apps}/components/${rel}`,
      aemPath: `/apps/${apps}/components/${rel}`,
      filename: format === 'standalone' ? `${folder}.cq_dialog.content.xml` : `${folder}.content.xml`,
      counts: {
        syntaxOk: validation.syntax.ok,
        generatorErrors: g.filter((x) => x.level === 'error').length,
        generatorWarnings: g.filter((x) => x.level === 'warning').length,
        aemErrors: validation.aem ? validation.aem.filter((x) => x.level === 'error').length : null,
        aemWarnings: validation.aem ? validation.aem.filter((x) => x.level === 'warning').length : null,
      },
    }
  })
}

export const hasProblems = (e: ComponentExport) => !e.counts.syntaxOk || e.counts.generatorErrors > 0 || (e.counts.aemErrors ?? 1) > 0

export function readme(project: Project, exports: ComponentExport[]): string {
  const lines = [
    `Aemora export: ${project.name}`,
    '',
    'WHAT THIS IS',
    'Dialog XML for AEM as a Cloud Service (Touch UI, Granite UI and Coral components only), generated by Aemora.',
    'It has NOT been tested on a running AEM instance. Try it on a development environment first.',
    '',
    'HOW TO USE IT',
    'The jcr_root folder mirrors an AEM project. Merge it into ui.apps/src/main/content/ in your project,',
    'next to the existing component folders, then build and deploy as you normally do.',
    'Files named _cq_dialog/.content.xml replace a component\'s dialog. Check before overwriting one that already exists.',
    '',
    'DIALOGS',
    ...exports.map((e) => {
      const flags = [e.edited ? 'hand-edited' : '', hasProblems(e) ? 'HAS PROBLEMS, see below' : 'checks passed'].filter(Boolean).join(', ')
      return `- ${e.component.name}  ->  ${e.aemPath}  (${flags})`
    }),
  ]
  const bad = exports.filter(hasProblems)
  if (bad.length) {
    lines.push('', 'PROBLEMS FOUND BY AEMORA\'S OWN CHECKS')
    for (const e of bad) {
      lines.push(`${e.component.name}:`)
      if (!e.validation.syntax.ok) lines.push(`  - XML is not well-formed: ${e.validation.syntax.message}`)
      for (const g of e.validation.generator.filter((x) => x.level === 'error')) lines.push(`  - ${g.message}`)
      for (const a of (e.validation.aem ?? []).filter((x) => x.level === 'error')) lines.push(`  - ${a.message} (${a.path})`)
    }
  }
  lines.push('', 'ALSO IN THIS ARCHIVE', '- aemora-project.json: the whole Aemora project. Import it into Aemora to continue editing.', '')
  return lines.join('\n')
}

export function buildBundle(project: Project): { zip: Uint8Array; files: ZipFile[]; exports: ComponentExport[] } {
  const exports = componentExports(project)
  const files: ZipFile[] = [
    { path: 'README.txt', content: readme(project, exports) },
    ...exports.map((e) => ({ path: e.zipPath, content: e.xml })),
    { path: 'aemora-project.json', content: exportProjectJson(project) },
  ]
  return { zip: createZip(files), files, exports }
}

export const bundleName = (project: Project) => `${kebab(project.name, 'aemora-project')}-dialogs.zip`
